#!/usr/bin/env python3
"""Write references/10-token-tables.md from tokens/tokens.json (run after build_tokens.py)."""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
T = json.loads((ROOT / "tokens" / "tokens.json").read_text())
prim = {}
for ramp, v in T["color"].items():
    if isinstance(v, dict) and "$value" not in v:
        for step, c in v.items():
            prim[f"{ramp}-{step}"] = c["$value"]
    else:
        prim[ramp] = v["$value"]


def resolve(v, depth=0):
    m = re.fullmatch(r"var\(--([\w-]+)\)", v)
    if not m or depth > 5:
        return v
    name = m.group(1)
    if name in prim:
        return prim[name]
    for theme in ("light",):
        if name in T["semantic"][theme]:
            return resolve(T["semantic"][theme][name]["$value"], depth + 1)
    return v


def rv(v):
    m = re.fullmatch(r"var\(--([\w-]+)\)", v)
    return f"`{m.group(1)}` {resolve(v)}" if m else f"{v}"


out = ["# Token tables", "",
       "Generated by `tools/build_token_docs.py` from `tokens/tokens.json`. Do not edit by hand.", "",
       "## Primitive ramps", "",
       "| ramp | 50 | 100 | 200 | 300 | 400 | 500 | 600 | 700 | 800 | 900 | 950 |",
       "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for ramp in ["gray", "blue", "green", "yellow", "orange", "red", "pink", "purple", "teal", "mint", "cyan", "pear", "papaya"]:
    out.append(f"| **{ramp}** | " + " | ".join(prim.get(f"{ramp}-{s}", "") for s in
                                                  ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"]) + " |")
out += ["", f"Extras: oat-50 {prim['oat-50']}, oat-200 {prim['oat-200']}, dark-gray {prim['dark-gray']}, "
        f"yellow-850 {prim.get('yellow-850', '')}. Alpha ramps `black-alpha-50…1000` and `white-alpha-50…1000` "
        "run 2%, 5%, 10%, 20%, 30%, 40%, 50%, 60%, 70%, 78%, 90%, 100%.", "",
        "## Semantic roles (light → dark)", "",
        "| role | light | dark |", "|---|---|---|"]
L, D = T["semantic"]["light"], T["semantic"]["dark"]
for k in L:
    out.append(f"| `--{k}` | {rv(L[k]['$value'])} | {rv(D[k]['$value'])} |")
out += ["", "## Text styles", "", "| class | family | size | weight | line-height | tracking |", "|---|---|---|---|---|---|"]
for k, v in T["textStyle"].items():
    t = v["$value"]
    out.append(f"| `.ts-{k}` | {t['fontFamily'].strip('{}').replace('font.', '')} | {t['fontSize']} | {t['fontWeight']} | {t['lineHeight']} | {t['letterSpacing']}"
               + (f" · {t['textTransform']}" if t.get("textTransform") else "") + " |")
out += ["", "## Scales", "",
        "**Space** (`--space-N`): " + ", ".join(f"{k} = {v['$value']}" for k, v in T["space"].items()), "",
        "**Radius** (`--radius-N`): " + ", ".join(f"{k} = {v['$value']}" for k, v in T["radius"].items()), "",
        "**Shadow** (`--shadow-N`): " + "; ".join(f"{k} = `{v['$value']}`" for k, v in T["shadow"].items()), "",
        "**Breakpoints** (min-width): " + ", ".join(f"{k} {v['$value']}" for k, v in T["breakpoint"].items()), "",
        "**z-index** (`--z-N`): " + ", ".join(f"{k} {v['$value']}" for k, v in T["zIndex"].items()), "",
        "**Motion**: " + ", ".join(f"`--{k}` {v['$value']}" for k, v in T["motion"].items()), "",
        "## Keyframes captured from production", "",
        ", ".join(f"`{k}`" for k in T["keyframes"]), ""]
(ROOT / "references" / "10-token-tables.md").write_text("\n".join(out))
print("wrote references/10-token-tables.md", len(out), "lines")
